/**
 * trainer-screen.js — the Practice screen: Stats | Chart | Drill.
 *
 * Pure rendering like render.js: reads game rules, the persisted stats object
 * and `options.ui.train` (tab + drill state owned by controls.js), returns HTML.
 * Everything strategic comes from the teaching modules (the chart and drill
 * grading are the computed advisor), never re-derived here.
 */

import { formatMoney } from '../engine/money.js';
import { cardFaceSvg } from '../assets/svg.js';
import { topMisses } from '../teaching/stats.js';
import { strategyChart, UPCARDS, HARD_ROWS, SOFT_ROWS, PAIR_ROWS } from '../teaching/chart.js';
import { DRILLS, legalMoves } from '../teaching/drill.js';
import { explainAction } from '../teaching/explain.js';
import { formatCostPerDollar } from '../teaching/mistakes.js';

const TABS = [
  ['stats', 'Stats'],
  ['chart', 'Chart'],
  ['drill', 'Drill'],
];
const MOVE_LABEL = { hit: 'Hit', stand: 'Stand', double: 'Double', split: 'Split', surrender: 'Surrender' };
const pct = (num, den) => (den ? `${Math.round((100 * num) / den)}%` : '—');
const signed = (cents) => (cents > 0 ? '+' : cents < 0 ? '−' : '') + formatMoney(Math.abs(cents));
const tile = (label, value, cls = '') =>
  `<div class="sim-stat"><span class="sim-stat-val ${cls}">${value}</span><span class="sim-stat-label">${label}</span></div>`;
const optBtn = (action, value, on, label) =>
  `<button class="btn sim-opt${on ? ' on' : ''}" data-action="${action}" data-value="${value}" aria-pressed="${on}">${label}</button>`;

// ── Stats ────────────────────────────────────────────────────────────────────

function renderStats(stats, ui) {
  const since = new Date(stats.since).toLocaleDateString();
  const misses = topMisses(stats, 6);
  const missRows = misses.length
    ? `<ul class="miss-list">${misses
        .map(
          (m) =>
            `<li><span class="miss-key">${m.key}</span><span class="miss-meta">wrong ${m.wrong} of ${m.seen}${
              m.wrong ? ` · ${formatCostPerDollar(m.cost / m.wrong)} per $1 each` : ''
            }</span></li>`
        )
        .join('')}</ul>`
    : '<p class="sim-status muted">No mistakes recorded yet — they will show up here.</p>';
  const confirm = ui.confirmStatsReset
    ? `<div class="confirm-bar" role="alertdialog" aria-label="Confirm stats reset">
         <span>Clear all stats?</span>
         <button class="btn" data-action="cancelResetStats">Cancel</button>
         <button class="btn primary" data-action="resetStats">Clear</button>
       </div>`
    : `<button class="btn train-reset" data-action="askResetStats">Reset stats</button>`;
  return `
    <p class="sim-caption">Since ${since}. Decisions are graded against your selected hint strategy.</p>
    <div class="sim-stats">
      ${tile('Hands', stats.hands.toLocaleString())}
      ${tile('Net', signed(stats.netCents), stats.netCents > 0 ? 'pos' : stats.netCents < 0 ? 'neg' : '')}
      ${tile('Correct', pct(stats.correct, stats.decisions))}
    </div>
    <div class="sim-stats">
      ${tile('Decisions', stats.decisions.toLocaleString())}
      ${tile('EV given up', `${stats.costEV.toFixed(2)} bets`, stats.costEV > 0 ? 'neg' : '')}
      ${tile('Insurance declined', `${stats.insurance.declined}/${stats.insurance.offered}`)}
    </div>
    <div class="sim-stats">
      ${tile('Drill', `${stats.drill.right}/${stats.drill.asked}`)}
      ${tile('Count quiz', `${stats.quiz.right}/${stats.quiz.asked}`)}
    </div>
    <h3 class="train-h">Most-missed hands</h3>
    ${missRows}
    ${confirm}`;
}

// ── Chart ────────────────────────────────────────────────────────────────────

const CELL_TEXT = { H: 'H', S: 'S', P: 'P', Dh: 'D', Ds: 'Ds', Rh: 'R', Rs: 'Rs' };
const CELL_CLASS = { H: 'c-h', S: 'c-s', P: 'c-p', Dh: 'c-d', Ds: 'c-d', Rh: 'c-r', Rs: 'c-r' };

function chartTable(title, rows, label, codes) {
  const head = UPCARDS.map((u) => `<th scope="col">${u}</th>`).join('');
  const body = rows
    .map(
      (r) =>
        `<tr><th scope="row">${label(r)}</th>${codes[r]
          .map((c) => `<td class="${CELL_CLASS[c] ?? ''}">${CELL_TEXT[c] ?? c}</td>`)
          .join('')}</tr>`
    )
    .join('');
  return `<h3 class="train-h">${title}</h3>
    <table class="chart"><thead><tr><th scope="col" class="chart-corner">You</th>${head}</tr></thead><tbody>${body}</tbody></table>`;
}

function renderChart(rules) {
  const chart = strategyChart(rules);
  const fewDecks = rules.shoe.numberOfDecks <= 2;
  return `
    <p class="sim-caption">Generated by the app's own advisor for the rules in play: ${rules.dealer.hitsSoft17 ? 'dealer hits soft 17' : 'dealer stands on soft 17'}, blackjack pays ${
      rules.payouts.blackjack === 1.5 ? '3:2' : rules.payouts.blackjack === 1.2 ? '6:5' : rules.payouts.blackjack + '×'
    }${rules.player.doubleAfterSplit ? ', double after split' : ''}${rules.player.surrender !== 'none' ? ', surrender' : ''}. Columns are the dealer's upcard.</p>
    <div class="chart-legend">
      <span class="c-h">H hit</span><span class="c-s">S stand</span><span class="c-d">D double (else hit)</span>
      <span class="c-d">Ds double (else stand)</span><span class="c-p">P split</span><span class="c-r">R / Rs surrender (else hit / stand)</span>
    </div>
    ${chartTable('Hard totals', HARD_ROWS.filter((t) => t >= 8), (t) => (t === 8 ? '≤8' : t), chart.hard)}
    <p class="sim-caption">Hard 18 and up: always stand.</p>
    ${chartTable('Soft totals', SOFT_ROWS, (x) => `A,${x}`, chart.soft)}
    ${chartTable('Pairs', PAIR_ROWS, (p) => `${p},${p}`, chart.pairs)}
    <p class="sim-caption">Infinite-deck model; deck-specific composition effects are not modeled.${
      fewDecks
        ? ' In this 1–2 deck game the in-game hint uses an exact finite-deck calculation, so it can differ from this chart on a few close hands.'
        : ''
    } Cross-check an authoritative chart for your rules.</p>`;
}

// ── Drill ────────────────────────────────────────────────────────────────────

function renderDrill(rules, drill) {
  const kinds = Object.entries(DRILLS)
    .map(([k, label]) => optBtn('drillKind', k, drill.kind === k, label))
    .join('');
  const q = drill.q;
  if (!q) return `<div class="sim-row drill-kinds">${kinds}</div>`;
  const cards = (list) => `<div class="hand">${list.map((c) => `<span class="card-slot">${cardFaceSvg(c)}</span>`).join('')}</div>`;
  let bottom;
  if (drill.result) {
    const { correct, rec, move } = drill.result;
    const why = rec.evs ? explainAction(rec, q.upcard) : '';
    bottom = `<div class="drill-feedback ${correct ? 'ok' : 'bad'}" role="status">
        <p class="drill-verdict">${correct ? 'Correct!' : `Not quite — you chose ${MOVE_LABEL[move]}.`} Basic strategy: <strong>${MOVE_LABEL[rec.action]}</strong></p>
        ${why ? `<p class="hint-why">${why}</p>` : ''}
      </div>
      <button class="btn primary drill-next" data-action="drillNext">Next hand</button>`;
  } else {
    bottom = `<div class="drill-moves">${legalMoves(q, rules)
      .map((m) => `<button class="btn drill-move" data-action="drillAnswer" data-value="${m}">${MOVE_LABEL[m]}</button>`)
      .join('')}</div>`;
  }
  return `
    <div class="sim-row drill-kinds">${kinds}</div>
    <p class="sim-caption drill-score">This session: ${drill.right}/${drill.asked} correct · streak ${drill.streak}</p>
    <div class="drill-table">
      <div class="drill-side"><span class="sim-label">Dealer</span>${cards([q.upcard])}</div>
      <div class="drill-side"><span class="sim-label">You</span>${cards(q.cards)}</div>
    </div>
    ${bottom}`;
}

// ── screen ───────────────────────────────────────────────────────────────────

export function renderTrainer(g, options) {
  const ui = options.ui || {};
  const train = ui.train || { tab: 'stats' };
  const stats = options.stats;
  const tabs = TABS.map(
    ([key, label]) =>
      `<button class="seg-btn${train.tab === key ? ' on' : ''}" data-action="trainTab" data-value="${key}" role="tab" aria-selected="${train.tab === key}">${label}</button>`
  ).join('');
  const body =
    train.tab === 'chart'
      ? renderChart(g.rules)
      : train.tab === 'drill'
        ? renderDrill(g.rules, train.drill)
        : renderStats(stats, ui);
  return `<div class="game sim-view train-view">
      <header class="topbar">
        <button class="btn icon" data-action="closeTrain" aria-label="Back to the table" title="Back to the table">←</button>
        <span class="sim-title">Practice</span>
      </header>
      <div class="seg train-tabs" role="tablist" aria-label="Practice sections">${tabs}</div>
      <div class="sim-scroll train-scroll">${body}</div>
    </div>`;
}
